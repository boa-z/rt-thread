# Generate the read-only SPI NAND partition description from
# pack/image_cfg.json so the BSP does not maintain a second, drifting
# copy of the NAND layout.
#
# Usage:
#   python gen_nand_parts.py --check
#   python gen_nand_parts.py --output build/spinand_parts_gen.h
#
# The generated header only describes the *linear* MTD view.  Partitions
# carrying an "nftl" object are marked non-linear and are intentionally
# not exposed as raw block devices (they belong to the vendor NFTL).

import argparse
import json
import os
import re
import sys

UNITS = {"k": 1024, "m": 1024 * 1024, "g": 1024 * 1024 * 1024}
DEFAULT_IMAGE_CFG = os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
    "pack", "image_cfg.json")


def strip_comments(text):
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    text = re.sub(r"//[^\n]*", "", text)
    return text


def parse_size(text):
    text = str(text).strip().lower()
    if text.endswith(("k", "m", "g")):
        return int(text[:-1]) * UNITS[text[-1]]
    return int(text, 0)


def load_layout(path):
    with open(path, "r", encoding="utf-8") as f:
        cfg = json.loads(strip_comments(f.read()))

    media = cfg["spi-nand"]
    info = cfg["image"]["info"]["media"]
    org = info["array_organization"][0]

    page_size = parse_size(org["page"])
    block_size = parse_size(org["block"])
    oob_size = parse_size(org["oob"])
    total_size = parse_size(media["size"])
    if page_size <= 0 or block_size <= 0 or total_size <= 0:
        raise ValueError("invalid NAND geometry in image_cfg.json")
    if block_size % page_size:
        raise ValueError("block size is not a multiple of page size")

    parts = []
    offset = 0
    for name, desc in media["partitions"].items():
        size_text = str(desc.get("size", "-")).strip()
        if size_text == "-":
            size = total_size - offset
        else:
            size = parse_size(size_text)
        if size <= 0:
            raise ValueError("partition %s has no size" % name)
        if offset % block_size:
            raise ValueError("partition %s is not block aligned (offset %d)" %
                             (name, offset))
        if size % block_size:
            raise ValueError("partition %s size %d is not block aligned" %
                             (name, size))
        if offset + size > total_size:
            raise ValueError("partition %s exceeds the NAND size" % name)
        linear = "nftl" not in desc
        parts.append({
            "name": name,
            "offset": offset,
            "size": size,
            "start_block": offset // block_size,
            "block_count": size // block_size,
            "linear": 1 if linear else 0,
        })
        offset += size

    return {
        "page_size": page_size,
        "oob_size": oob_size,
        "block_size": block_size,
        "total_size": total_size,
        "total_blocks": total_size // block_size,
        "parts": parts,
    }


def validate(layout):
    last_end = 0
    for part in layout["parts"]:
        if part["offset"] < last_end:
            raise ValueError("partition %s overlaps the previous one" %
                             part["name"])
        last_end = part["offset"] + part["size"]
    if layout["total_blocks"] * layout["block_size"] != layout["total_size"]:
        raise ValueError("NAND size is not a whole number of erase blocks")
    if not any(p["linear"] for p in layout["parts"]):
        raise ValueError("no linear MTD partition found")


def summarize(layout):
    print("NAND: %d MiB, page %d, block %d, oob %d, %d blocks" % (
        layout["total_size"] // (1024 * 1024), layout["page_size"],
        layout["block_size"], layout["oob_size"], layout["total_blocks"]))
    for part in layout["parts"]:
        print("  %-9s start=0x%08x size=0x%08x blocks=%3u..%3u %s" % (
            part["name"], part["offset"], part["size"],
            part["start_block"],
            part["start_block"] + part["block_count"] - 1,
            "MTD" if part["linear"] else "NFTL (not exposed as linear MTD)"))


def emit_header(layout):
    lines = []
    lines.append("/*")
    lines.append(" * Auto-generated by tools/gen_nand_parts.py from "
                 "pack/image_cfg.json.")
    lines.append(" * Do not edit; change image_cfg.json and rebuild.")
    lines.append(" *")
    lines.append(" * SPDX-License-Identifier: Apache-2.0")
    lines.append(" */")
    lines.append("#ifndef __SPINAND_PARTS_GEN_H__")
    lines.append("#define __SPINAND_PARTS_GEN_H__")
    lines.append("")
    lines.append("#define SPINAND_CFG_PAGE_SIZE      %du" % layout["page_size"])
    lines.append("#define SPINAND_CFG_OOB_SIZE       %du" % layout["oob_size"])
    lines.append("#define SPINAND_CFG_BLOCK_SIZE     %du" % layout["block_size"])
    lines.append("#define SPINAND_CFG_TOTAL_BLOCKS   %du" % layout["total_blocks"])
    lines.append("")
    lines.append('#include "aic_board.h"')
    lines.append("")
    lines.append("#define SPINAND_PART_COUNT %du" % len(layout["parts"]))
    lines.append("")
    lines.append("static const struct spinand_part_desc "
                 "spinand_parts[SPINAND_PART_COUNT] =")
    lines.append("{")
    for part in layout["parts"]:
        lines.append('    {"%s", %uu, %uu, %uu},' % (
            part["name"], part["start_block"], part["block_count"],
            part["linear"]))
    lines.append("};")
    lines.append("")
    lines.append("#endif /* __SPINAND_PARTS_GEN_H__ */")
    lines.append("")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--image", default=DEFAULT_IMAGE_CFG,
                        help="path to pack/image_cfg.json")
    parser.add_argument("--output", help="generated header path")
    parser.add_argument("--check", action="store_true",
                        help="validate only, do not write a header")
    args = parser.parse_args()

    try:
        layout = load_layout(args.image)
        validate(layout)
    except Exception as exc:
        print("gen_nand_parts: %s" % exc, file=sys.stderr)
        return 1

    summarize(layout)
    if args.output and not args.check:
        out_dir = os.path.dirname(os.path.abspath(args.output))
        if out_dir:
            os.makedirs(out_dir, exist_ok=True)
        content = emit_header(layout)
        try:
            with open(args.output, "r", encoding="utf-8") as f:
                if f.read() == content:
                    print("unchanged: %s" % args.output)
                    return 0
        except OSError:
            pass
        with open(args.output, "w", encoding="utf-8", newline="\n") as f:
            f.write(content)
        print("written: %s" % args.output)
    return 0


if __name__ == "__main__":
    sys.exit(main())
