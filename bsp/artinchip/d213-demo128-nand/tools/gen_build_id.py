# Generate build/build_id_gen.h before compilation.
#
# The Build ID is derived from the target, the git SHA, the effective
# rtconfig.h hash and the UTC build time.  The time component makes every
# build unique so the HIL can reject a board that still runs an older image.

import argparse
import datetime
import hashlib
import os
import subprocess
import sys


def git(root, *args):
    try:
        return subprocess.check_output(
            ["git"] + list(args), cwd=root, text=True,
            stderr=subprocess.DEVNULL).strip()
    except Exception:
        return "unknown"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", required=True)
    parser.add_argument("--target", default="d213-demo128-nand")
    parser.add_argument("--rtconfig", default=None)
    args = parser.parse_args()

    bsp = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
    root = os.path.normpath(os.path.join(bsp, "..", "..", ".."))

    git_sha = git(root, "rev-parse", "--short=12", "HEAD")
    dirty = bool(git(root, "status", "--porcelain", "--", "bsp/artinchip"))
    if dirty:
        git_sha += "-dirty"

    rtconfig = args.rtconfig or os.path.join(bsp, "rtconfig.h")
    if os.path.isfile(rtconfig):
        with open(rtconfig, "rb") as f:
            config_hash = hashlib.sha256(f.read()).hexdigest()
    else:
        config_hash = "unknown"

    built_at = datetime.datetime.now(datetime.timezone.utc).strftime(
        "%Y-%m-%dT%H:%M:%SZ")
    build_id = "%s-%s-%s-%s" % (args.target, git_sha, config_hash[:8],
                                built_at)

    text = """/*
 * Generated by tools/gen_build_id.py.  Do not edit.
 */
#ifndef AIC_BUILD_ID_GEN_H
#define AIC_BUILD_ID_GEN_H

#define AIC_BUILD_ID          "%s"
#define AIC_BUILD_GIT_SHA     "%s"
#define AIC_BUILD_CONFIG_HASH "%s"
#define AIC_BUILD_TARGET      "%s"
#define AIC_BUILD_TIME        "%s"

#endif
""" % (build_id, git_sha, config_hash, args.target, built_at)

    os.makedirs(os.path.dirname(os.path.abspath(args.output)), exist_ok=True)
    tmp = args.output + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        f.write(text)
    os.replace(tmp, args.output)
    print("build_id: %s" % build_id)


if __name__ == "__main__":
    sys.exit(main())
